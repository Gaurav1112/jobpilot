/**
 * Build-time compile of the place data (`src/app/geo/data/**.yaml`) into the pure module `src/app/geo/data.generated.ts`.
 *
 *   node --run geo:gen
 *
 * The YAML is the source of truth; the generated module is what runs. Agent code reaches the place tables through
 * `norm.ts`, and the containment scan forbids file I/O there, so nothing at run time reads the YAML. A drift test
 * (`tests/app/geo/places.test.ts`) renders in memory and checks the committed file is byte-identical. Output is
 * deterministic: object keys sorted, array order kept (a country's `cities` then `states` order is its spelling order).
 */
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { pathToFileURL } from 'node:url';
import { parse } from 'yaml';
import { z } from 'zod';
import { BASE_PLACES } from '../src/app/geo/base.js';

const repo = join(import.meta.dirname, '..');
export const GEO_DATA_DIR = join(repo, 'src/app/geo/data');
export const GEO_GENERATED = join(repo, 'src/app/geo/data.generated.ts');

const Country = z.strictObject({
  code: z.string().regex(/^[A-Z]{2}$/),
  country: z.string().min(1),
  display: z.string().min(1),
  regions: z.array(z.string()),
  utcOffsets: z.array(z.number()),
  zoneWords: z.array(z.string()),
  cities: z.array(z.string()),
  states: z.array(z.string()),
  offices: z.record(z.string(), z.strictObject({ display: z.string().min(1), aliases: z.array(z.string().min(1)).min(1) })),
  benefitsNote: z.string().optional(),
});
const Regions = z.record(z.string().regex(/^[A-Z]{2}$/), z.array(z.string()));
const Slug = z.string().regex(/^[a-z0-9]+(?:-[a-z0-9]+)*$/);
/** `jobicy-geos.yaml` (profiles Task 15): Jobicy's geo slugs per country code, and per region for a code without an entry. */
const JobicyGeos = z.strictObject({
  countries: z.record(z.string().regex(/^[A-Z]{2}$/), z.array(Slug).min(1)),
  regions: z.record(z.string(), Slug),
});

/** A region token must be a place name, and never `worldwide` (a residence scope always adds that itself). */
function checkRegions(where: string, regions: readonly string[]): void {
  for (const r of regions) {
    if (r === 'worldwide' || !Object.hasOwn(BASE_PLACES, r)) throw new Error(`${where}: region ${JSON.stringify(r)} is not a region place name`);
  }
}

/** `v` with every object's keys sorted (arrays keep their order), so the rendering is deterministic. */
function sortKeys(v: unknown): unknown {
  if (Array.isArray(v)) return v.map(sortKeys);
  if (v !== null && typeof v === 'object') {
    return Object.fromEntries(Object.keys(v).sort().map((k) => [k, sortKeys((v as Record<string, unknown>)[k])]));
  }
  return v;
}

/** The generated module's text for the YAML under `dir`. Throws on any invalid file. */
export function renderGeo(dir: string = GEO_DATA_DIR): string {
  const countries: Record<string, z.infer<typeof Country>> = {};
  for (const f of readdirSync(join(dir, 'countries')).filter((x) => x.endsWith('.yaml')).sort()) {
    const c = Country.parse(parse(readFileSync(join(dir, 'countries', f), 'utf8')));
    if (`${c.code}.yaml` !== f) throw new Error(`countries/${f}: code ${c.code} does not match the file name`);
    if (!Object.hasOwn(BASE_PLACES, c.country)) throw new Error(`countries/${f}: country ${JSON.stringify(c.country)} is not a place name`);
    checkRegions(`countries/${f}`, c.regions);
    countries[c.code] = c;
  }
  const regions = Regions.parse(parse(readFileSync(join(dir, 'regions.yaml'), 'utf8')));
  for (const [code, rs] of Object.entries(regions)) checkRegions(`regions.yaml ${code}`, rs);
  const jobicy = JobicyGeos.parse(parse(readFileSync(join(dir, 'jobicy-geos.yaml'), 'utf8')));
  for (const [code, slugs] of Object.entries(jobicy.countries)) {
    if (!Object.hasOwn(regions, code)) throw new Error(`jobicy-geos.yaml: ${code} is not a code in regions.yaml`);
    if (new Set(slugs).size !== slugs.length) throw new Error(`jobicy-geos.yaml: ${code} repeats a slug`);
  }
  checkRegions('jobicy-geos.yaml regions', Object.keys(jobicy.regions));
  return [
    '// GENERATED by scripts/gen-geo.ts from src/app/geo/data/**.yaml — do not edit; run node --run geo:gen',
    "import type { CountryData } from './base.js';",
    '',
    `export const COUNTRIES: Readonly<Record<string, CountryData>> = ${JSON.stringify(sortKeys(countries), null, 2)};`,
    '',
    `export const REGIONS: Readonly<Record<string, readonly string[]>> = ${JSON.stringify(sortKeys(regions), null, 2)};`,
    '',
    `export const JOBICY_GEO_SLUGS: { readonly countries: Readonly<Record<string, readonly string[]>>; readonly regions: Readonly<Record<string, string>> } = ${JSON.stringify(sortKeys(jobicy), null, 2)};`,
    '',
  ].join('\n');
}

if (process.argv[1] !== undefined && import.meta.url === pathToFileURL(process.argv[1]).href) {
  writeFileSync(GEO_GENERATED, renderGeo());
  console.log(`wrote ${GEO_GENERATED}`);
}
