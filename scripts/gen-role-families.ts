/**
 * Build-time compile of `src/app/profiles/data/role-families.yaml` into the pure module
 * `src/app/profiles/families.generated.ts`.
 *
 *   node --run families:gen
 *
 * The YAML is the source of truth; the generated module is what runs (agent code reads it, and the containment scan
 * forbids file I/O there). A drift test (`tests/app/role-families.test.ts`) renders in memory and checks the committed
 * file is byte-identical. The YAML must name exactly the twelve families of `ROLE_FAMILY_IDS`; output is in that order.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { pathToFileURL } from 'node:url';
import { parse } from 'yaml';
import { z } from 'zod';
import { ROLE_FAMILY_IDS } from '../src/app/profiles/families.js';

const repo = join(import.meta.dirname, '..');
export const FAMILIES_YAML = join(repo, 'src/app/profiles/data/role-families.yaml');
export const FAMILIES_GENERATED = join(repo, 'src/app/profiles/families.generated.ts');

const Term = z.string().trim().min(1);
const Family = z.strictObject({ display: Term, titles: z.array(Term).min(1), bonusWords: z.array(Term) });
const Families = z.record(z.enum(ROLE_FAMILY_IDS), Family);

/** The generated module's text for `file`. Throws on an invalid file, or one that lacks or adds a family. */
export function renderRoleFamilies(file: string = FAMILIES_YAML): string {
  const families = Families.parse(parse(readFileSync(file, 'utf8')));
  const ordered = Object.fromEntries(ROLE_FAMILY_IDS.map((id) => {
    const f = families[id];
    return [id, { display: f.display, titles: f.titles, bonusWords: f.bonusWords }];
  }));
  return [
    '// GENERATED by scripts/gen-role-families.ts from src/app/profiles/data/role-families.yaml — do not edit; run node --run families:gen',
    "import type { RoleFamilyData, RoleFamilyId } from './families.js';",
    '',
    `export const ROLE_FAMILIES: Readonly<Record<RoleFamilyId, RoleFamilyData>> = ${JSON.stringify(ordered, null, 2)};`,
    '',
  ].join('\n');
}

if (process.argv[1] !== undefined && import.meta.url === pathToFileURL(process.argv[1]).href) {
  writeFileSync(FAMILIES_GENERATED, renderRoleFamilies());
  console.log(`wrote ${FAMILIES_GENERATED}`);
}
